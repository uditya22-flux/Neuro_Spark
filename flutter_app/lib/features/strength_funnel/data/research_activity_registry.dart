List<ResearchActivityStem> researchStemsForSector(String sectorId) {
  return kResearchActivityStems.where((s) => s.sectorIds.contains(sectorId)).toList();
}

ResearchActivityStem? researchStemById(String id) {
  for (final stem in kResearchActivityStems) {
    if (stem.id == id) return stem;
  }
  return null;
}

